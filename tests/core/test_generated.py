"""Generated/vendored-file detection (core.generated). High precision: banners in the head,
known generated names, vendored dirs -- never a bare size threshold."""

import pytest

from auryn.core.generated import detection_enabled, is_generated


def test_antlr_banner():
    head = b"# Generated from PlSqlParser.g4 by ANTLR 4.9.3\nfrom antlr4 import *\n"
    assert is_generated("pkg/grammar/PlSqlParser.py", head)  # the file that was our parse tall-pole


def test_protobuf_banner():
    head = b"# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
    assert is_generated("x/foo_pb2.py", head)


def test_go_code_generated_line():
    assert is_generated("x/foo.go", b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")


def test_at_generated_marker():
    assert is_generated("a/b.ts", b"/* @generated */\nexport const x = 1\n")


def test_min_js_by_filename():
    assert is_generated("static/js/vendor/graphology.umd.min.js", b"!function(){}();")


def test_vendored_dir():
    assert is_generated("node_modules/left-pad/index.js", b"module.exports = 1\n")


@pytest.mark.parametrize("path", [
    "deps/RediSearch/bin/linux-x64-release/search-community/_deps/boost-src/libs/mpl/preprocess.py",
    "_deps/boost-src/__init__.py",
    r"build\_deps\boost-src\example.py",
])
def test_cmake_downloaded_dependency_is_vendored(path):
    assert is_generated(path, b"print 'Python 2'\n") == "vendored dir"


@pytest.mark.parametrize("path", ["deps/helper.py", "src/deps.py", "src/_deps.py"])
def test_dependency_names_do_not_exclude_project_source(path):
    assert is_generated(path, b"def helper():\n    pass\n") is None


def test_hand_written_is_not_flagged():
    head = b'"""A normal module."""\nimport os\n\n\ndef f():\n    return 1\n'
    assert is_generated("pkg/mod.py", head) is None


def test_generated_init_is_kept_as_package_marker():
    # A generated `__init__.py` is a structural package marker: dropping it would re-root every
    # sibling module's dotted path (`pkg.mod` -> `src.…pkg.mod`) and break cross-repo linkage.
    # Keep it despite the banner (regression for huggingface_hub inference/_generated/types).
    head = b"# This file is auto-generated by scripts/gen.py. Do not edit.\nfrom .a import A\n"
    assert is_generated("src/pkg/inference/_generated/types/__init__.py", head) is None


def test_vendored_init_is_still_dropped():
    # ...but a package marker inside a vendored tree is still excluded with that tree.
    assert is_generated("node_modules/foo/__init__.py", b"# @generated\n")


def test_prose_about_generation_without_banner_is_not_flagged():
    # Mentions codegen in prose but has no generator banner at the head -> keep it.
    head = b"# Parser notes\n\nThis module parses code; we hand-write everything here.\n"
    assert is_generated("pkg/notes.py", head) is None


def test_midline_mention_is_not_flagged():
    # A banner phrase appearing MID-line (prose/comment about generated files, like this detector's
    # own source) must NOT trip -- a real banner is anchored at the start of a top-of-file comment.
    head = b'# High-precision "this file is generated" banners, matched case-insensitively.\n'
    assert is_generated("pkg/detector.py", head) is None
    head2 = b'"""We detect files that say they were generated by a tool."""\nimport os\n'
    assert is_generated("pkg/mod.py", head2) is None


def test_banner_below_license_header_is_flagged():
    # Banners often sit just under a short license/coding header -> still caught within the scan window.
    head = b"# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
    assert is_generated("x/foo_pb2.py", head)


def test_env_opt_out(monkeypatch):
    monkeypatch.delenv("AURYN_INCLUDE_GENERATED", raising=False)
    assert detection_enabled() is True
    monkeypatch.setenv("AURYN_INCLUDE_GENERATED", "1")
    assert detection_enabled() is False

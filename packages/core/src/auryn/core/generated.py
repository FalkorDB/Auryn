"""Detect machine-generated / vendored source so ingestion can skip it by default.

Generated code -- ANTLR parsers, protobuf stubs, minified JS bundles -- is usually huge, churns
as a unit, carries no hand-written intent, and drowns the real architecture in hubs/god-nodes
(one 160k-line generated ANTLR parser was the single parse tall-pole and ~61k of a repo's nodes).
Skipping it is faster, lighter, and yields a cleaner graph. Opt back in with
`AURYN_INCLUDE_GENERATED=1`.

Detection is deliberately **high precision**: an explicit generator banner in the file *head*, a
well-known generated filename, or a vendored directory. Never a bare size/line threshold -- that
would silently drop legitimate large hand-written files (the per-file parse timeout is the guard
for those). Callers apply this at the source listing seam so every language honors it at once.
"""

from __future__ import annotations

import os
import re

# A generator banner is always at the very top; scan only the head so this stays cheap on listing.
HEAD_BYTES = 4096

# How many leading lines to scan for a banner. A real banner is line 1-ish, but some sit below a
# shebang / coding / short license header -- 40 lines covers those without reading the whole file.
_SCAN_LINES = 40

# Comment punctuation / whitespace stripped from a line's LEFT before matching, so a banner in
# `# ...`, `// ...`, `/* ... */`, `-- ...`, `<!-- ... -->`, `; ...` all reduce to the banner text.
# Quotes are deliberately NOT stripped: a real banner never opens with a quote, but a comment that
# *quotes* a banner phrase (like this module's own docs) does -- keeping the quote blocks that match.
_COMMENT_LEAD_RE = re.compile(r"""^[\s/#*!;\-<>=.]*""")

# High-precision "this file is generated" banners, matched case-insensitively and ANCHORED to the
# start of a (comment-stripped) line. Anchoring is what makes it precise: a mid-sentence mention of
# "this file is generated" in prose or docs (or in this very module's comments) is NOT a banner.
_BANNER_RE = re.compile(
    r"@(?:auto-?)?generated\b"
    r"|auto-?generated by\b"
    r"|generated by the protocol buffer compiler"          # protobuf
    r"|generated from .{0,80}? by antlr"                    # ANTLR (our PlSqlParser.py)
    r"|generated by swig\b"                                 # SWIG
    r"|code generated .{0,80}? do not edit"                 # Go convention
    r"|generated by [\w.\-/ ]{0,40}?[;.]? *do not edit"     # "Generated by X; DO NOT EDIT"
    r"|this (?:file|code) (?:is|was) (?:auto[- ]?)?generated\b"
    r"|do not edit[.!]?(?: this file)?[.!]? .{0,40}?generated",  # "DO NOT EDIT. ... generated"
    re.IGNORECASE,
)


def _banner(head: bytes) -> str | None:
    """The generator banner at the start of one of the first `_SCAN_LINES` lines, normalized, else
    None. Matching is anchored to the line start (after stripping comment punctuation) so only a
    real top-of-file banner counts -- never a mid-line prose mention of the word 'generated'."""
    text = head[:HEAD_BYTES].decode("utf-8", "replace")
    for line in text.splitlines()[:_SCAN_LINES]:
        stripped = _COMMENT_LEAD_RE.sub("", line, count=1)
        m = _BANNER_RE.match(stripped)
        if m:
            return " ".join(m.group(0).split())[:48]
    return None

# Well-known generated filenames / minified bundles (checked on the basename).
_GENERATED_NAME_RE = re.compile(
    r"(?:\.pb\.go|_pb2\.py|_pb2_grpc\.py|\.pb\.cc|\.pb\.h|\.g\.dart|\.designer\.cs"
    r"|\.min\.js|\.min\.css|\.min\.mjs|\.bundle\.js)$",
    re.IGNORECASE,
)

# Vendored dirs (matched at any path level). Some ingestors already list a few of these in their
# own excluded_dir_names; keeping them here means the policy is on by default without user config.
_VENDORED_DIRS = frozenset(
    {"node_modules", "vendor", "third_party", "site-packages", "bower_components", "_deps"}
)


def detection_enabled() -> bool:
    """On by default. `AURYN_INCLUDE_GENERATED=1` (or true/yes) keeps generated/vendored files."""
    return os.environ.get("AURYN_INCLUDE_GENERATED", "").strip().lower() not in ("1", "true", "yes")


def is_generated(rel_path: str, head: bytes) -> str | None:
    """A short reason string if `rel_path` (whose first bytes are `head`) is machine-generated or
    vendored, else None. `head` need only be the first ~HEAD_BYTES bytes -- markers live at the top,
    so a caller can read just the head rather than the whole blob."""
    posix = rel_path.replace("\\", "/")
    parts = posix.split("/")
    if _VENDORED_DIRS.intersection(parts[:-1]):
        return "vendored dir"
    if _GENERATED_NAME_RE.search(parts[-1]):
        return "generated filename"
    # A package marker (`__init__.py`) is structural, not noise: its mere PRESENCE on disk defines
    # the package and anchors every sibling module's import-root -> dotted path -> cross-repo linkage
    # key. Dropping a *generated* `__init__.py` on a banner alone silently re-roots those siblings
    # (`pkg.mod` -> `src.…pkg.mod`), polluting their linkage keys and breaking cross-repo symbol
    # healing (observed on huggingface_hub's generated `inference/_generated/types/__init__.py`). The
    # package marker is never the huge/churning file this filter targets, so keep it. (A marker inside
    # a vendored tree -- node_modules/ etc. -- is still dropped by the dir check above.)
    if parts[-1] == "__init__.py":
        return None
    marker = _banner(head)
    if marker:
        return f'banner "{marker}"'
    return None
